-- Alerta emitida. CLAVE_EVENTO evita duplicados ante reprocesos (TR-16, EC-06)
create table ale_alerta (
  alerta_id           number generated by default on null as identity,
  clave_evento        varchar2(300) not null,
  regla_id            number,
  regla_version       number,
  modulo_codigo       varchar2(10) not null,
  tipo                varchar2(30) not null,
  nivel               varchar2(2),
  titulo              varchar2(1000) not null,
  motivo              varchar2(4000) not null,
  mencion_id          number,
  sesion_id           number,
  intervencion_id     number,
  estado_validacion   varchar2(20) not null,
  enlace              varchar2(2000),
  enlace_evidencia    varchar2(2000),
  fecha_deteccion     timestamp not null,
  fecha_emision       timestamp default systimestamp not null,
  estado_seguimiento  varchar2(20) default 'PENDIENTE' not null,
  responsable_id      number,
  situacion_id        number,
  observaciones       varchar2(4000),
  acciones            varchar2(4000),
  fecha_cierre        date,
  activa              varchar2(1) default 'S' not null,
  constraint ale_alerta_pk primary key (alerta_id),
  constraint ale_alerta_clave_uk unique (clave_evento),
  constraint ale_alerta_regla_fk foreign key (regla_id) references ale_regla,
  constraint ale_alerta_men_fk foreign key (mencion_id) references men_mencion,
  constraint ale_alerta_resp_fk foreign key (responsable_id) references seg_usuario,
  constraint ale_alerta_sit_fk foreign key (situacion_id) references ale_situacion,
  constraint ale_alerta_tipo_ck check (tipo in ('REGLA','SESION_NIVEL','SIN_TRANSMISION','INICIO_SESION',
       'INTEGRACION','COBERTURA','PERMISO','SIMULTANEIDAD')),
  constraint ale_alerta_nivel_ck check (nivel in ('N1','N2','N3','N4')),
  constraint ale_alerta_val_ck check (estado_validacion in ('PENDIENTE_REVISION','VALIDADA','NO_APLICA')),
  constraint ale_alerta_seg_ck check (estado_seguimiento in ('PENDIENTE','EN_ATENCION','CERRADA')),
  constraint ale_alerta_act_ck check (activa in ('S','N')),
  constraint ale_alerta_cierre_ck check (estado_seguimiento <> 'CERRADA' or fecha_cierre is not null)
);
create index ale_alerta_fec_ix on ale_alerta (modulo_codigo, fecha_emision);

