-- Reglas de alerta (TR-16). Guardan umbral, periodo de comparación y versión
create table ale_regla (
  regla_id          number generated by default on null as identity,
  nombre            varchar2(300) not null,
  propietario_id    number        not null,
  tipo_condicion    varchar2(30)  not null,
  modulos           varchar2(100) default 'PRE:RED:EC' not null,
  tema_id           number,
  vocero_id         number,
  institucion_id    number,
  sentimiento_id    number,
  terminos          varchar2(4000),
  nivel_minimo      varchar2(2),
  umbral_pct        number,
  ventana_horas     number default 24,
  periodo_comparacion_horas number default 168,
  canales           varchar2(100) default 'PORTAL' not null,
  frecuencia        varchar2(20)  default 'INMEDIATA' not null,
  estado            varchar2(20)  default 'ACTIVA' not null,
  version           number default 1 not null,
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint ale_regla_pk primary key (regla_id),
  constraint ale_regla_prop_fk foreign key (propietario_id) references seg_usuario,
  constraint ale_regla_tema_fk foreign key (tema_id) references cat_tema,
  constraint ale_regla_voc_fk foreign key (vocero_id) references cat_vocero,
  constraint ale_regla_ins_fk foreign key (institucion_id) references cat_institucion,
  constraint ale_regla_sen_fk foreign key (sentimiento_id) references cat_categoria,
  constraint ale_regla_tipo_ck check (tipo_condicion in ('COINCIDENCIA','COMBINACION','AUMENTO_VOLUMEN',
      'CAMBIO_SENTIMIENTO','ENTRE_CANALES','SESION_NIVEL','COBERTURA')),
  constraint ale_regla_frec_ck check (frecuencia in ('INMEDIATA','HORARIA','DIARIA','SEMANAL')),
  constraint ale_regla_est_ck check (estado in ('ACTIVA','SUSPENDIDA','ELIMINADA')),
  constraint ale_regla_umb_ck check (tipo_condicion not in ('AUMENTO_VOLUMEN','CAMBIO_SENTIMIENTO')
      or (umbral_pct is not null and periodo_comparacion_horas is not null))
);

-- Destinatarios adicionales de una regla (además del propietario)
create table ale_regla_destinatario (
  regla_id    number not null,
  usuario_id  number not null,
  constraint ale_regla_dest_pk primary key (regla_id, usuario_id),
  constraint ale_regla_dest_r_fk foreign key (regla_id) references ale_regla on delete cascade,
  constraint ale_regla_dest_u_fk foreign key (usuario_id) references seg_usuario
);

-- Situación: agrupa alertas referidas a un mismo hecho (TR-17)
create table ale_situacion (
  situacion_id  number generated by default on null as identity,
  titulo        varchar2(500) not null,
  descripcion   varchar2(4000),
  estado        varchar2(20) default 'ABIERTA' not null,
  creado_por    varchar2(255) default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en     date default on null sysdate not null,
  constraint ale_situacion_pk primary key (situacion_id),
