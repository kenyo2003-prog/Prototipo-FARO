-- Cuentas de redes sociales monitoreadas (RED-01)
create table red_cuenta (
  cuenta_id       number generated by default on null as identity,
  plataforma_id   number        not null,
  identificador   varchar2(300) not null,
  nombre          varchar2(300),
  url             varchar2(1000),
  propia          varchar2(1) default 'N' not null,
  vocero_id       number,
  medio_id        number,
  institucion_id  number,
  prioridad_id    number,
  estado          varchar2(20) default 'VIGENTE' not null,
  disponible      varchar2(1) default 'S' not null,
  fecha_verificacion date,
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint red_cuenta_pk primary key (cuenta_id),
  constraint red_cuenta_uk unique (plataforma_id, identificador),
  constraint red_cuenta_pla_fk foreign key (plataforma_id) references cat_categoria,
  constraint red_cuenta_voc_fk foreign key (vocero_id) references cat_vocero,
  constraint red_cuenta_med_fk foreign key (medio_id) references cat_medio,
  constraint red_cuenta_ins_fk foreign key (institucion_id) references cat_institucion,
  constraint red_cuenta_pri_fk foreign key (prioridad_id) references cat_categoria,
  constraint red_cuenta_propia_ck check (propia in ('S','N')),
  constraint red_cuenta_disp_ck check (disponible in ('S','N')),
  constraint red_cuenta_est_ck check (estado in ('VIGENTE','INACTIVO'))
);

-- Soporte / pieza de monitoreo: nota, post, sesión, proyecto, comentario...
-- (ORIGEN_REF, FUENTE) es la clave de idempotencia ante reintentos (PRE-02, RED-02)
create table men_soporte (
  soporte_id          number generated by default on null as identity,
  modulo_codigo       varchar2(10)  not null,
  tipo_soporte        varchar2(20)  not null,
  fuente              varchar2(30)  not null,
  origen_ref          varchar2(500) not null,
  titulo              varchar2(1000),
  contenido           clob,
  url                 varchar2(2000),
  medio_id            number,
  cuenta_id           number,
  autor_vocero_id     number,
  autor_texto         varchar2(300),
  fecha_publicacion   timestamp     not null,
  fecha_captura       timestamp default systimestamp not null,
  formato             varchar2(30),
  origen_manual       varchar2(1) default 'N' not null,
  historico_migrado   varchar2(1) default 'N' not null,
  tiene_menciones     varchar2(1) default 'S' not null,
  hash_contenido      varchar2(64),
  duplicado_de_id     number,
  republicacion_de_id number,
  sesion_id           number,
  proyecto_id         number,
  ejecucion_int_id    number,
  metadatos           clob,
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint men_soporte_pk primary key (soporte_id),
  constraint men_soporte_origen_uk unique (fuente, origen_ref),
  constraint men_soporte_mod_fk foreign key (modulo_codigo) references seg_modulo,
  constraint men_soporte_med_fk foreign key (medio_id) references cat_medio,
  constraint men_soporte_cta_fk foreign key (cuenta_id) references red_cuenta,
  constraint men_soporte_aut_fk foreign key (autor_vocero_id) references cat_vocero,
  constraint men_soporte_dup_fk foreign key (duplicado_de_id) references men_soporte,
  constraint men_soporte_rep_fk foreign key (republicacion_de_id) references men_soporte,
  constraint men_soporte_eje_fk foreign key (ejecucion_int_id) references int_ejecucion,
  constraint men_soporte_tipo_ck check (tipo_soporte in ('NOTA','POST','PUBLICACION_PROPIA','COMENTARIO','SESION','PROYECTO','DOCUMENTO')),
  constraint men_soporte_man_ck check (origen_manual in ('S','N')),
  constraint men_soporte_his_ck check (historico_migrado in ('S','N')),
  constraint men_soporte_tm_ck check (tiene_menciones in ('S','N')),
  constraint men_soporte_meta_json_ck check (metadatos is json)
);
create index men_soporte_fec_ix on men_soporte (modulo_codigo, fecha_publicacion);
create index men_soporte_url_ix on men_soporte (url);
create index men_soporte_hash_ix on men_soporte (hash_contenido);

-- Mención: unidad de análisis (glosario). Estado controlado por FARO_MEN:
-- INGERIDA → CLASIFICADA → VALIDADA | DESCARTADA (TR-15)
create table men_mencion (
  mencion_id        number generated by default on null as identity,
  soporte_id        number        not null,
  modulo_codigo     varchar2(10)  not null,
  fragmento         varchar2(4000) not null,
  estado            varchar2(20) default 'INGERIDA' not null,
  tema_id           number,
  pilar_id          number,
  sentimiento_id    number,
  vocero_id         number,
  afiliacion_id     number,
  institucion_id    number,
  medio_id          number,
  contexto_id       number,
  protagonismo_id   number,
  relevancia_id     number,
  criticidad_id     number,
  nivel_alerta      varchar2(2),
  vocero_sin_identificar varchar2(1) default 'N' not null,
  requiere_revision varchar2(1) default 'N' not null,
  correccion_humana varchar2(1) default 'N' not null,
  cat_version_id    number,
  ejecucion_ia_id   number,
  validado_por      varchar2(255),
  fecha_validacion  date,
  motivo_descarte   varchar2(4000),
  descartado_por    varchar2(255),
  fecha_descarte    date,
  fecha_mencion     timestamp     not null,
  periodo           varchar2(7) generated always as (to_char(fecha_mencion,'YYYY-MM')) virtual,
  intervencion_id   number,
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint men_mencion_pk primary key (mencion_id),
  constraint men_mencion_sop_fk foreign key (soporte_id) references men_soporte,
  constraint men_mencion_mod_fk foreign key (modulo_codigo) references seg_modulo,
  constraint men_mencion_tema_fk foreign key (tema_id) references cat_tema,
  constraint men_mencion_pil_fk foreign key (pilar_id) references cat_pilar,
  constraint men_mencion_sen_fk foreign key (sentimiento_id) references cat_categoria,
  constraint men_mencion_voc_fk foreign key (vocero_id) references cat_vocero,
  constraint men_mencion_afi_fk foreign key (afiliacion_id) references cat_afiliacion,
  constraint men_mencion_ins_fk foreign key (institucion_id) references cat_institucion,
  constraint men_mencion_med_fk foreign key (medio_id) references cat_medio,
  constraint men_mencion_ctx_fk foreign key (contexto_id) references cat_categoria,
  constraint men_mencion_pro_fk foreign key (protagonismo_id) references cat_categoria,
  constraint men_mencion_rel_fk foreign key (relevancia_id) references cat_categoria,
  constraint men_mencion_cri_fk foreign key (criticidad_id) references cat_categoria,
  constraint men_mencion_cv_fk foreign key (cat_version_id) references cat_version,
  constraint men_mencion_eje_fk foreign key (ejecucion_ia_id) references ia_ejecucion,
  constraint men_mencion_est_ck check (estado in ('INGERIDA','CLASIFICADA','VALIDADA','DESCARTADA')),
  constraint men_mencion_niv_ck check (nivel_alerta in ('N1','N2','N3','N4')),
  constraint men_mencion_vsi_ck check (vocero_sin_identificar in ('S','N')),
  constraint men_mencion_rr_ck check (requiere_revision in ('S','N')),
  constraint men_mencion_ch_ck check (correccion_humana in ('S','N')),
  constraint men_mencion_desc_ck check (estado <> 'DESCARTADA' or motivo_descarte is not null)
);
create index men_mencion_sop_ix on men_mencion (soporte_id);
create index men_mencion_est_ix on men_mencion (modulo_codigo, estado, fecha_mencion);
create index men_mencion_voc_ix on men_mencion (vocero_id);
create index men_mencion_ins_ix on men_mencion (institucion_id);
create index men_mencion_tema_ix on men_mencion (tema_id);

-- Resultado automático conservado, aunque luego se corrija (PRE-03, RED-04, EC-05)
create table men_clasificacion_auto (
  clasificacion_id  number generated by default on null as identity,
  mencion_id        number not null,
  ejecucion_ia_id   number,
  lote_id           number,
  tema_id           number,
  pilar_id          number,
  sentimiento_id    number,
  vocero_id         number,
  institucion_id    number,
  medio_id          number,
  nivel_alerta      varchar2(2),
  confianza         number(5,4),
  requiere_revision varchar2(1) default 'N' not null,
  justificacion     varchar2(4000),
  cat_version_id    number,
  vigente           varchar2(1) default 'S' not null,
  fecha             timestamp default systimestamp not null,
  constraint men_clasif_auto_pk primary key (clasificacion_id),
  constraint men_clasif_auto_men_fk foreign key (mencion_id) references men_mencion,
  constraint men_clasif_auto_eje_fk foreign key (ejecucion_ia_id) references ia_ejecucion,
  constraint men_clasif_auto_lot_fk foreign key (lote_id) references ia_lote,
  constraint men_clasif_auto_vig_ck check (vigente in ('S','N'))
);
create index men_clasif_auto_men_ix on men_clasificacion_auto (mencion_id);

-- Historial de cambios de estado y de campo (TR-15, PRE-03)
create table men_historial (
  historial_id    number generated by default on null as identity,
  mencion_id      number        not null,
  tipo            varchar2(20)  not null,
  campo           varchar2(60),
  valor_anterior  varchar2(4000),
  valor_nuevo     varchar2(4000),
  excepcional     varchar2(1) default 'N' not null,
  motivo          varchar2(4000),
  usuario         varchar2(255) default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  fecha           timestamp default systimestamp not null,
  constraint men_historial_pk primary key (historial_id),
  constraint men_historial_men_fk foreign key (mencion_id) references men_mencion,
  constraint men_historial_tipo_ck check (tipo in ('ESTADO','CORRECCION','ATRIBUCION','REPROCESO','FUSION'))
);
create index men_historial_men_ix on men_historial (mencion_id);

-- Matriz de transiciones válidas de estado (TR-15 refinamiento)
create table men_transicion (
  estado_origen   varchar2(20) not null,
  estado_destino  varchar2(20) not null,
  excepcional     varchar2(1) default 'N' not null,
  requiere_motivo varchar2(1) default 'N' not null,
  constraint men_transicion_pk primary key (estado_origen, estado_destino)
);

-- Evidencia verificable (TR-15): enlace, fragmento, tiempo de video, página…
create table men_evidencia (
  evidencia_id      number generated by default on null as identity,
  soporte_id        number not null,
  mencion_id        number,
  tipo              varchar2(20) not null,
  url               varchar2(2000),
  fragmento         varchar2(4000),
  segundo_inicio    number,
  segundo_fin       number,
  pagina            number,
  articulo          varchar2(200),
  archivo           blob,
  archivo_mime      varchar2(200),
  archivo_nombre    varchar2(400),
  disponible        varchar2(1) default 'S' not null,
  fecha_verificacion timestamp,
  fecha_captura     timestamp default systimestamp not null,
  constraint men_evidencia_pk primary key (evidencia_id),
  constraint men_evidencia_sop_fk foreign key (soporte_id) references men_soporte,
  constraint men_evidencia_men_fk foreign key (mencion_id) references men_mencion,
  constraint men_evidencia_tipo_ck check (tipo in ('ENLACE','FRAGMENTO','TIEMPO_VIDEO','PAGINA','CAPTURA','DOCUMENTO','TRANSCRIPCION')),
  constraint men_evidencia_disp_ck check (disponible in ('S','N'))
);
create index men_evidencia_men_ix on men_evidencia (mencion_id);
create index men_evidencia_sop_ix on men_evidencia (soporte_id);

-- Propuestas de duplicidad (TR-14): distingue captura repetida de republicación
create table men_duplicado (
  duplicado_id     number generated by default on null as identity,
  soporte_id       number not null,
  soporte_ref_id   number not null,
  criterio         varchar2(20) not null,
  similitud        number(5,2),
  clasificacion    varchar2(20) not null,
  estado           varchar2(20) default 'PROPUESTO' not null,
  resuelto_por     varchar2(255),
  fecha_resolucion date,
  comentario       varchar2(4000),
  fecha            timestamp default systimestamp not null,
  constraint men_duplicado_pk primary key (duplicado_id),
  constraint men_duplicado_uk unique (soporte_id, soporte_ref_id),
  constraint men_duplicado_s_fk foreign key (soporte_id) references men_soporte,
  constraint men_duplicado_r_fk foreign key (soporte_ref_id) references men_soporte,
  constraint men_duplicado_cri_ck check (criterio in ('ORIGEN','URL','CONTENIDO')),
  constraint men_duplicado_cla_ck check (clasificacion in ('CAPTURA_REPETIDA','REPUBLICACION')),
  constraint men_duplicado_est_ck check (estado in ('PROPUESTO','CONFIRMADO','RECHAZADO'))
);
