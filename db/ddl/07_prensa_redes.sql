-- Equivalencias entre categorías anteriores y catálogo común (PRE-01)
create table mig_equivalencia (
  equivalencia_id  number generated by default on null as identity,
  campo_origen     varchar2(60)  not null,
  valor_origen     varchar2(500) not null,
  catalogo_destino varchar2(30)  not null,
  registro_destino_id number,
  observacion      varchar2(4000),
  aprobado_por     varchar2(255),
  constraint mig_equivalencia_pk primary key (equivalencia_id),
  constraint mig_equivalencia_uk unique (campo_origen, valor_origen)
);

-- Registros históricos en staging antes de homologar (PRE-01)
create table mig_prensa_staging (
  staging_id       number generated by default on null as identity,
  lote             varchar2(60) not null,
  origen_ref       varchar2(500) not null,
  fecha            date,
  medio            varchar2(500),
  titulo           varchar2(2000),
  texto            clob,
  url              varchar2(2000),
  tema             varchar2(500),
  pilar            varchar2(500),
  sentimiento      varchar2(100),
  vocero           varchar2(500),
  tiene_mencion    varchar2(1),
  estado           varchar2(20) default 'PENDIENTE' not null,
  observacion      varchar2(4000),
  soporte_id       number,
  constraint mig_prensa_staging_pk primary key (staging_id),
  constraint mig_prensa_staging_est_ck check (estado in ('PENDIENTE','HOMOLOGADO','INCOMPLETO','SIN_EQUIVALENCIA','ERROR'))
);

-- Informe de conciliación por periodo e indicador (PRE-01)
create table mig_conciliacion (
  conciliacion_id  number generated by default on null as identity,
  lote             varchar2(60) not null,
  periodo          varchar2(7)  not null,
  indicador        varchar2(30) not null,
  valor_original   number,
  valor_recalculado number,
  diferencia       number generated always as (valor_recalculado - valor_original) virtual,
  registros_no_homologables number default 0 not null,
  justificacion    varchar2(4000),
  estado           varchar2(30) default 'PENDIENTE' not null,
  aprobado_por     varchar2(255),
  fecha_aprobacion date,
  constraint mig_conciliacion_pk primary key (conciliacion_id),
  constraint mig_conciliacion_uk unique (lote, periodo, indicador),
  constraint mig_conciliacion_est_ck check (estado in ('PENDIENTE','COINCIDE','DIFERENCIA_JUSTIFICADA','APROBADO','RECHAZADO'))
);

-- Política de tratamiento de comentarios ofensivos/anónimos (RED-03 · Rojo)
-- La captura de comentarios queda bloqueada hasta que exista una política APROBADA vigente
create table red_politica_comentarios (
  politica_id      number generated by default on null as identity,
  version          number not null,
  tratamiento_ofensivo varchar2(20) not null,
  tratamiento_anonimo  varchar2(20) not null,
  descripcion      varchar2(4000) not null,
  vigente_desde    date not null,
  vigente_hasta    date,
  estado           varchar2(20) default 'BORRADOR' not null,
  aprobada_por     varchar2(255),
  fecha_aprobacion date,
  constraint red_politica_pk primary key (politica_id),
  constraint red_politica_ver_uk unique (version),
  constraint red_politica_of_ck check (tratamiento_ofensivo in ('CONSERVAR','ANONIMIZAR','DESCARTAR')),
  constraint red_politica_an_ck check (tratamiento_anonimo in ('CONSERVAR','ANONIMIZAR','DESCARTAR')),
  constraint red_politica_est_ck check (estado in ('BORRADOR','APROBADA','RETIRADA'))
);

-- Métricas de publicaciones propias con fecha de actualización (RED-03)
create table red_metrica (
  metrica_id       number generated by default on null as identity,
  soporte_id       number not null,
  fecha_actualizacion timestamp default systimestamp not null,
  impresiones      number,
  alcance          number,
  reacciones       number,
  comentarios      number,
  compartidos      number,
  reproducciones   number,
  clics            number,
  constraint red_metrica_pk primary key (metrica_id),
  constraint red_metrica_sop_fk foreign key (soporte_id) references men_soporte
);
create index red_metrica_sop_ix on red_metrica (soporte_id, fecha_actualizacion);

-- Análisis agregado de comentarios por publicación y tema (RED-03).
-- No se crean voceros a partir de autores de comentarios.
create table red_comentario_agregado (
  agregado_id      number generated by default on null as identity,
  soporte_id       number not null,
  tema_id          number,
  tema_emergente   varchar2(500),
  cantidad         number default 0 not null,
  positivos        number default 0 not null,
  neutros          number default 0 not null,
  negativos        number default 0 not null,
  ofensivos_tratados number default 0 not null,
  anonimos_tratados  number default 0 not null,
  politica_id      number not null,
  fecha_calculo    timestamp default systimestamp not null,
  constraint red_comentario_agr_pk primary key (agregado_id),
  constraint red_comentario_agr_s_fk foreign key (soporte_id) references men_soporte,
  constraint red_comentario_agr_t_fk foreign key (tema_id) references cat_tema,
  constraint red_comentario_agr_p_fk foreign key (politica_id) references red_politica_comentarios
);

-- Evaluaciones de confiabilidad (RED-05)
create table red_evaluacion (
  evaluacion_id     number generated by default on null as identity,
  nombre            varchar2(300) not null,
  metodo_seleccion  varchar2(30)  not null,
  tamano_muestra    number not null,
  universo          number,
  fecha_desde       date not null,
  fecha_hasta       date not null,
  modelo            varchar2(200),
  prompt_version_id number,
  cat_version_id    number,
  metodo_version    varchar2(20) default '1.0' not null,
  estado            varchar2(20) default 'EN_CURSO' not null,
  coincidencia_general number(5,2),
  kappa_sentimiento number(6,4),
  evaluador         varchar2(255) default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  fecha             date default sysdate not null,
  fecha_cierre      date,
  constraint red_evaluacion_pk primary key (evaluacion_id),
  constraint red_evaluacion_met_ck check (metodo_seleccion in ('ALEATORIO_SIMPLE','ESTRATIFICADO_TEMA','ESTRATIFICADO_PLATAFORMA')),
  constraint red_evaluacion_est_ck check (estado in ('EN_CURSO','CERRADA'))
);

-- Ítems: la clasificación humana se registra a ciegas (sin ver el automático)
create table red_evaluacion_item (
  item_id           number generated by default on null as identity,
  evaluacion_id     number not null,
  mencion_id        number not null,
  auto_tema_id      number,
  auto_pilar_id     number,
  auto_sentimiento_id number,
  humano_tema_id    number,
  humano_pilar_id   number,
  humano_sentimiento_id number,
  evaluado          varchar2(1) default 'N' not null,
  fecha_evaluacion  timestamp,
  constraint red_evaluacion_item_pk primary key (item_id),
  constraint red_evaluacion_item_uk unique (evaluacion_id, mencion_id),
  constraint red_evaluacion_item_e_fk foreign key (evaluacion_id) references red_evaluacion on delete cascade,
  constraint red_evaluacion_item_m_fk foreign key (mencion_id) references men_mencion
);
