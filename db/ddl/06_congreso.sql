-- Proyectos de ley desde SIAPLEY (EC-08..EC-11). NUMERO es la identidad.
create table ec_proyecto (
  proyecto_id        number generated by default on null as identity,
  numero             varchar2(30)  not null,
  periodo_parlamentario varchar2(20),
  fecha_presentacion date          not null,
  titulo             varchar2(2000) not null,
  proponente         varchar2(1000),
  grupo_parlamentario varchar2(300),
  resumen            clob,
  palabras_clave     varchar2(2000),
  estado_actual      varchar2(300),
  comision_actual    varchar2(300),
  url_expediente     varchar2(2000),
  texto_completo     clob,
  documento_legible  varchar2(1) default 'S' not null,
  acumulado_en_id    number,
  -- propuesta automática y revisión (EC-09, EC-10)
  tema_id            number,
  alcance            varchar2(1000),
  menciona_banco     varchar2(1),
  prioridad_id       number,
  descripcion        clob,
  implicancia        clob,
  sustento           clob,
  origen_textos      varchar2(20) default 'AUTOMATICO' not null,
  estado_revision    varchar2(20) default 'PENDIENTE' not null,
  motivo_exclusion   varchar2(4000),
  validado_por       varchar2(255),
  fecha_validacion   date,
  ejecucion_ia_id    number,
  ultima_sincronizacion timestamp,
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint ec_proyecto_pk primary key (proyecto_id),
  constraint ec_proyecto_num_uk unique (numero),
  constraint ec_proyecto_acu_fk foreign key (acumulado_en_id) references ec_proyecto,
  constraint ec_proyecto_tema_fk foreign key (tema_id) references cat_tema,
  constraint ec_proyecto_pri_fk foreign key (prioridad_id) references cat_categoria,
  constraint ec_proyecto_eje_fk foreign key (ejecucion_ia_id) references ia_ejecucion,
  constraint ec_proyecto_leg_ck check (documento_legible in ('S','N')),
  constraint ec_proyecto_mb_ck check (menciona_banco in ('S','N')),
  constraint ec_proyecto_ot_ck check (origen_textos in ('AUTOMATICO','REVISADO')),
  constraint ec_proyecto_er_ck check (estado_revision in ('PENDIENTE','REQUIERE_REVISION','VALIDADO','EXCLUIDO')),
  constraint ec_proyecto_exc_ck check (estado_revision <> 'EXCLUIDO' or motivo_exclusion is not null),
  constraint ec_proyecto_sus_json_ck check (sustento is json)
);
create index ec_proyecto_fec_ix on ec_proyecto (fecha_presentacion);

-- Versiones de estado, comisión, acumulaciones y textos sustitutorios (EC-08)
create table ec_proyecto_version (
  version_id      number generated by default on null as identity,
  proyecto_id     number not null,
  fecha_evento    date   not null,
  tipo_evento     varchar2(30) not null,
  estado          varchar2(300),
  comision        varchar2(300),
  descripcion     varchar2(4000),
  documento_url   varchar2(2000),
  datos           clob,
  sincronizado_en timestamp default systimestamp not null,
  constraint ec_proyecto_version_pk primary key (version_id),
  constraint ec_proyecto_version_p_fk foreign key (proyecto_id) references ec_proyecto,
  constraint ec_proyecto_version_t_ck check (tipo_evento in ('PRESENTACION','CAMBIO_ESTADO','DECRETO_COMISION','ACUMULACION',
