  contexto_previo   clob,
  contexto_posterior clob,
  hablante_id       number,
  hablante_propuesto_id number,
  hablante_estado   varchar2(20) default 'SIN_IDENTIFICAR' not null,
  confianza         number(5,4),
  evidencia_confianza varchar2(4000),
  criterio_umbral   number(5,4),
  nivel             varchar2(2),
  tipo_deteccion    varchar2(30) not null,
