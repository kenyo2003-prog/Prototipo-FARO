  constraint ec_intervencion_tra_fk foreign key (transmision_id) references ec_transmision,
  constraint ec_intervencion_hab_fk foreign key (hablante_id) references cat_vocero,
  constraint ec_intervencion_hpr_fk foreign key (hablante_propuesto_id) references cat_vocero,
  constraint ec_intervencion_tema_fk foreign key (tema_id) references cat_tema,
  constraint ec_intervencion_he_ck check (hablante_estado in ('PROPUESTO','SIN_IDENTIFICAR','CORREGIDO','CONFIRMADO')),
  constraint ec_intervencion_niv_ck check (nivel in ('N1','N2','N3','N4')),
  constraint ec_intervencion_td_ck check (tipo_deteccion in ('MENCION_BANCO','TEMA_INTERES','DEBATE_PL','VOTACION','DECISION_PL'))
);

