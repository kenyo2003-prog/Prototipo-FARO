-- Criterios de monitoreo (EC-01, RED-01): términos ligados al catálogo común
-- de temas, con escalas controladas y precedencia documentada
create table mon_criterio (
  criterio_id     number generated by default on null as identity,
  modulo_codigo   varchar2(10)  not null,
  tema_id         number        not null,
  tipo            varchar2(20)  default 'TERMINO' not null,
  expresion       varchar2(1000) not null,
  interes_id      number,
  prioridad_id    number,
  criticidad_id   number,
  nivel_alerta    varchar2(2),
  precedencia     number default 100 not null,
  estado          varchar2(20) default 'VIGENTE' not null,
  version         number default 1 not null,
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint mon_criterio_pk primary key (criterio_id),
  constraint mon_criterio_mod_fk foreign key (modulo_codigo) references seg_modulo,
  constraint mon_criterio_tema_fk foreign key (tema_id) references cat_tema,
  constraint mon_criterio_int_fk foreign key (interes_id) references cat_categoria,
  constraint mon_criterio_pri_fk foreign key (prioridad_id) references cat_categoria,
  constraint mon_criterio_cri_fk foreign key (criticidad_id) references cat_categoria,
  constraint mon_criterio_tipo_ck check (tipo in ('TERMINO','VARIANTE','EXPRESION','REGEX')),
  constraint mon_criterio_niv_ck check (nivel_alerta in ('N1','N2','N3','N4')),
  constraint mon_criterio_est_ck check (estado in ('VIGENTE','INACTIVO'))
);

-- Comisiones e instancias (EC-01: comisiones de monitoreo íntegro)
create table ec_comision (
  comision_id        number generated by default on null as identity,
  codigo             varchar2(30)  not null,
  nombre             varchar2(300) not null,
  instancia_id       number        not null,
  monitoreo_integro  varchar2(1) default 'N' not null,
  prioridad_id       number,
  regla_titulo       varchar2(1000),
  estado             varchar2(20) default 'VIGENTE' not null,
  constraint ec_comision_pk primary key (comision_id),
  constraint ec_comision_cod_uk unique (codigo),
  constraint ec_comision_ins_fk foreign key (instancia_id) references cat_categoria,
  constraint ec_comision_pri_fk foreign key (prioridad_id) references cat_categoria,
  constraint ec_comision_mi_ck check (monitoreo_integro in ('S','N'))
);

-- Sesiones de la agenda (EC-02)
create table ec_sesion (
  sesion_id          number generated by default on null as identity,
  origen_ref         varchar2(300) not null,
  instancia_id       number        not null,
  comision_id        number,
  titulo             varchar2(1000) not null,
  fecha_programada   timestamp     not null,
  fecha_inicio_real  timestamp,
  fecha_fin_real     timestamp,
  estado             varchar2(20) default 'PROGRAMADA' not null,
  prioridad_id       number,
  priorizada         varchar2(1) default 'N' not null,
  fuente_citacion    varchar2(1000),
  aviso_previo_enviado varchar2(1) default 'N' not null,
  video_retirado     varchar2(1) default 'N' not null,
  procesamiento      varchar2(20) default 'PENDIENTE' not null,
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint ec_sesion_pk primary key (sesion_id),
  constraint ec_sesion_ori_uk unique (origen_ref),
  constraint ec_sesion_ins_fk foreign key (instancia_id) references cat_categoria,
  constraint ec_sesion_com_fk foreign key (comision_id) references ec_comision,
  constraint ec_sesion_pri_fk foreign key (prioridad_id) references cat_categoria,
  constraint ec_sesion_est_ck check (estado in ('PROGRAMADA','EN_CURSO','CAPTURADA','NO_CUBIERTA','CANCELADA','REPROGRAMADA')),
  constraint ec_sesion_proc_ck check (procesamiento in ('PENDIENTE','EN_COLA','EN_PROCESO','COMPLETO','INCOMPLETO')),
  constraint ec_sesion_pz_ck check (priorizada in ('S','N')),
  constraint ec_sesion_vr_ck check (video_retirado in ('S','N'))
);
create index ec_sesion_fec_ix on ec_sesion (fecha_programada);

-- Historial de estados de sesión con origen y responsable (EC-02)
create table ec_sesion_estado (
  sesion_estado_id number generated by default on null as identity,
