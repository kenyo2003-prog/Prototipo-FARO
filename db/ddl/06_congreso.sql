-- Vínculo proyecto ↔ sesión / acuerdo (EC-11)
create table ec_proyecto_sesion (
  vinculo_id      number generated by default on null as identity,
  proyecto_id     number not null,
  sesion_id       number not null,
  acuerdo_id      number,
  tipo            varchar2(20) default 'DEBATE' not null,
  origen          varchar2(20) default 'AUTOMATICO' not null,
  evidencia       varchar2(4000),
  estado          varchar2(20) default 'SUGERIDO' not null,
  usuario         varchar2(255),
  fecha           timestamp default systimestamp not null,
  constraint ec_proyecto_sesion_pk primary key (vinculo_id),
  constraint ec_proyecto_sesion_uk unique (proyecto_id, sesion_id, tipo),
  constraint ec_proyecto_sesion_p_fk foreign key (proyecto_id) references ec_proyecto,
  constraint ec_proyecto_sesion_s_fk foreign key (sesion_id) references ec_sesion,
  constraint ec_proyecto_sesion_a_fk foreign key (acuerdo_id) references ec_acuerdo,
  constraint ec_proyecto_sesion_t_ck check (tipo in ('DEBATE','ACUERDO','VOTACION','MENCION')),
  constraint ec_proyecto_sesion_o_ck check (origen in ('AUTOMATICO','MANUAL')),
  constraint ec_proyecto_sesion_e_ck check (estado in ('SUGERIDO','CONFIRMADO','RECHAZADO'))
);

