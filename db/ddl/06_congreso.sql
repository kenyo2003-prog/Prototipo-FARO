  constraint ec_sesion_estado_o_ck check (origen in ('AUTOMATICO','MANUAL','INTEGRACION'))
);

-- Transmisiones asociadas (EC-03). Sin almacenamiento de video.
create table ec_transmision (
  transmision_id   number generated by default on null as identity,
  sesion_id        number,
  url              varchar2(2000) not null,
  canal            varchar2(200),
  titulo           varchar2(1000),
  origen           varchar2(20) default 'AUTOMATICO' not null,
  es_reanudacion   varchar2(1) default 'N' not null,
  orden            number default 1 not null,
  inicio           timestamp,
  fin              timestamp,
  estado_proceso   varchar2(20) default 'PENDIENTE' not null,
  ultimo_segundo   number default 0 not null,
  audio_temporal   varchar2(1000),
  error            varchar2(4000),
  constraint ec_transmision_pk primary key (transmision_id),
  constraint ec_transmision_url_uk unique (url),
  constraint ec_transmision_ses_fk foreign key (sesion_id) references ec_sesion,
  constraint ec_transmision_ori_ck check (origen in ('AUTOMATICO','MANUAL')),
  constraint ec_transmision_est_ck check (estado_proceso in ('PENDIENTE','EN_COLA','EN_PROCESO','COMPLETA','INCOMPLETA','FALLIDA')),
  constraint ec_transmision_rea_ck check (es_reanudacion in ('S','N'))
);

-- Segmentos de transcripción (texto; nunca video/audio) para búsqueda (EC-03, EC-12)
create table ec_transcripcion (
  segmento_id      number generated by default on null as identity,
  transmision_id   number not null,
  segundo_inicio   number not null,
  segundo_fin      number not null,
  texto            varchar2(4000) not null,
  hablante_etiqueta varchar2(300),
  creado_en        timestamp default systimestamp not null,
  constraint ec_transcripcion_pk primary key (segmento_id),
  constraint ec_transcripcion_uk unique (transmision_id, segundo_inicio),
  constraint ec_transcripcion_t_fk foreign key (transmision_id) references ec_transmision
);

-- Intervenciones detectadas con ±60 s de contexto (EC-03, EC-04)
create table ec_intervencion (
