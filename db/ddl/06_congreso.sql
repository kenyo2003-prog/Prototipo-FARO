  fecha_validacion  date,
  observaciones     varchar2(4000),
  constraint ec_acuerdo_pk primary key (acuerdo_id),
  constraint ec_acuerdo_ses_fk foreign key (sesion_id) references ec_sesion,
  constraint ec_acuerdo_pro_fk foreign key (proyecto_id) references ec_proyecto,
  constraint ec_acuerdo_int_fk foreign key (intervencion_id) references ec_intervencion,
  constraint ec_acuerdo_tip_fk foreign key (tipo_acto_id) references cat_categoria,
  constraint ec_acuerdo_est_ck check (estado in ('PROPUESTO','CORREGIDO','VALIDADO')),
  constraint ec_acuerdo_auto_json_ck check (valor_automatico is json)
