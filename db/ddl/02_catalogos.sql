--------------------------------------------------------------------------------
-- FARO · 02 · Catálogos maestros versionados
-- HU: TR-04 a TR-10 · Arquitectura C3 "Catálogos maestros", §7 Catálogo
-- Regla: cada cambio aprobado incrementa la versión del registro, deja una
-- instantánea en CAT_HISTORIAL y genera una nueva versión global (CAT_VERSION)
-- que se registra en cada clasificación (TR-06, TR-10).
--------------------------------------------------------------------------------

-- Versión global del catálogo común (una fila por cambio aprobado)
create table cat_version (
  cat_version_id  number generated by default on null as identity,
  fecha           date default sysdate not null,
  responsable     varchar2(255) default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  descripcion     varchar2(4000),
  afecta_historico varchar2(1) default 'N' not null,
  constraint cat_version_pk primary key (cat_version_id),
  constraint cat_version_afh_ck check (afecta_historico in ('S','N'))
);

-- Pilares (TR-05)
create table cat_pilar (
  pilar_id        number generated by default on null as identity,
  codigo          varchar2(30)   not null,
  nombre          varchar2(200)  not null,
  definicion      varchar2(4000) not null,
  ejemplos        varchar2(4000),
  estado          varchar2(20) default 'VIGENTE' not null,
  version         number default 1 not null,
  vigente_desde   date default sysdate not null,
  justificacion   varchar2(4000),
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint cat_pilar_pk primary key (pilar_id),
  constraint cat_pilar_cod_uk unique (codigo),
  constraint cat_pilar_estado_ck check (estado in ('VIGENTE','INACTIVO'))
);

-- Temas (TR-04). Términos/variantes/ejemplos se usan en detección y prompts.
-- PILAR_ORIENTATIVO_ID es sólo orientativo: no fuerza asignación (TR-05).
create table cat_tema (
  tema_id              number generated by default on null as identity,
  codigo               varchar2(30)   not null,
  nombre               varchar2(200)  not null,
  descripcion          varchar2(4000) not null,
  criterios_aplicacion varchar2(4000),
  terminos             varchar2(4000),
  variantes            varchar2(4000),
  ejemplos             varchar2(4000),
  pilar_orientativo_id number,
  estado               varchar2(20) default 'VIGENTE' not null,
  version              number default 1 not null,
  vigente_desde        date default sysdate not null,
  justificacion        varchar2(4000),
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint cat_tema_pk primary key (tema_id),
  constraint cat_tema_cod_uk unique (codigo),
  constraint cat_tema_pilar_fk foreign key (pilar_orientativo_id) references cat_pilar,
  constraint cat_tema_estado_ck check (estado in ('VIGENTE','INACTIVO'))
);

-- Tipos de categoría complementaria (TR-06) y valores controlados
-- Ejemplos de tipo: SENTIMIENTO, TIPO_VOCERO, TIPO_INSTITUCION, TIPO_MEDIO,
-- CONTEXTO, PROTAGONISMO, PRIORIDAD, CRITICIDAD, INTERES, NIVEL_ALERTA,
-- TIPO_HITO, TIPO_ACTO, INSTANCIA, PLATAFORMA, RELEVANCIA
create table cat_categoria_tipo (
  tipo_codigo   varchar2(30)  not null,
  nombre        varchar2(200) not null,
  descripcion   varchar2(4000),
  editable      varchar2(1) default 'S' not null,
  constraint cat_categoria_tipo_pk primary key (tipo_codigo),
  constraint cat_categoria_tipo_ed_ck check (editable in ('S','N'))
);

create table cat_categoria (
  categoria_id    number generated by default on null as identity,
  tipo_codigo     varchar2(30)   not null,
  codigo          varchar2(30)   not null,
  nombre          varchar2(200)  not null,
  definicion      varchar2(4000),
  orden           number(4) default 0 not null,
  valor_numerico  number,
  modulos         varchar2(100) default 'PRE:RED:EC' not null,
  estado          varchar2(20) default 'VIGENTE' not null,
  version         number default 1 not null,
  vigente_desde   date default sysdate not null,
  justificacion   varchar2(4000),
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint cat_categoria_pk primary key (categoria_id),
  constraint cat_categoria_uk unique (tipo_codigo, codigo),
  constraint cat_categoria_tipo_fk foreign key (tipo_codigo) references cat_categoria_tipo,
  constraint cat_categoria_estado_ck check (estado in ('VIGENTE','INACTIVO'))
);

-- Instituciones (TR-07). FUSIONADA_EN_ID apunta al registro superviviente.
