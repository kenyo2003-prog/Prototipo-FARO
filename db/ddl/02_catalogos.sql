-- Afiliaciones fechadas vocero-institución (TR-09). Se admiten simultáneas;
-- las superposiciones dudosas se advierten desde FARO_CAT.
create table cat_afiliacion (
  afiliacion_id   number generated by default on null as identity,
  vocero_id       number        not null,
  institucion_id  number        not null,
  cargo           varchar2(300) not null,
  fecha_inicio    date          not null,
  fecha_fin       date,
  principal       varchar2(1) default 'S' not null,
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint cat_afiliacion_pk primary key (afiliacion_id),
  constraint cat_afiliacion_voc_fk foreign key (vocero_id) references cat_vocero,
  constraint cat_afiliacion_ins_fk foreign key (institucion_id) references cat_institucion,
  constraint cat_afiliacion_fec_ck check (fecha_fin is null or fecha_fin >= fecha_inicio),
  constraint cat_afiliacion_pri_ck check (principal in ('S','N'))
);
create index cat_afiliacion_voc_ix on cat_afiliacion (vocero_id, fecha_inicio);

-- Instantáneas versionadas de cada registro de catálogo (TR-04, TR-06, TR-10)
create table cat_historial (
  historial_id    number generated by default on null as identity,
  catalogo        varchar2(30)  not null,
  registro_id     number        not null,
  version         number        not null,
  cat_version_id  number,
  snapshot        clob          not null,
  responsable     varchar2(255) default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  fecha           date default sysdate not null,
  justificacion   varchar2(4000),
  constraint cat_historial_pk primary key (historial_id),
  constraint cat_historial_ver_fk foreign key (cat_version_id) references cat_version,
  constraint cat_historial_json_ck check (snapshot is json),
  constraint cat_historial_uk unique (catalogo, registro_id, version)
);

-- Propuestas de alta/modificación del especialista (TR-07..TR-10)
create table cat_propuesta (
  propuesta_id     number generated by default on null as identity,
  catalogo         varchar2(30)  not null,
  tipo             varchar2(20)  not null,
  registro_id      number,
  datos            clob          not null,
  justificacion    varchar2(4000) not null,
  modulo_codigo    varchar2(10),
  propuesto_por    varchar2(255) default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  fecha_propuesta  date default sysdate not null,
  estado           varchar2(20) default 'PENDIENTE' not null,
  revisado_por     varchar2(255),
  fecha_revision   date,
  comentario       varchar2(4000),
  integrar_con_id  number,
  tratamiento_historico varchar2(20) default 'CONSERVAR' not null,
  cat_version_id   number,
  constraint cat_propuesta_pk primary key (propuesta_id),
  constraint cat_propuesta_cat_ck check (catalogo in ('TEMA','PILAR','CATEGORIA','INSTITUCION','MEDIO','VOCERO','AFILIACION')),
  constraint cat_propuesta_tipo_ck check (tipo in ('ALTA','MODIFICACION','BAJA')),
  constraint cat_propuesta_est_ck check (estado in ('PENDIENTE','APROBADA','RECHAZADA','INTEGRADA')),
  constraint cat_propuesta_trh_ck check (tratamiento_historico in ('CONSERVAR','REPROCESAR')),
  constraint cat_propuesta_json_ck check (datos is json),
  constraint cat_propuesta_ver_fk foreign key (cat_version_id) references cat_version
);
