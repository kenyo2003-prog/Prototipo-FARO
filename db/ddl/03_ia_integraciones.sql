-- Plantilla de prompt por módulo y tarea (TR-11)
create table ia_prompt (
  prompt_id      number generated by default on null as identity,
  codigo         varchar2(60)  not null,
  nombre         varchar2(200) not null,
  modulo_codigo  varchar2(10)  not null,
  tarea          varchar2(30)  not null,
  descripcion    varchar2(4000),
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint ia_prompt_pk primary key (prompt_id),
  constraint ia_prompt_cod_uk unique (codigo),
  constraint ia_prompt_mod_fk foreign key (modulo_codigo) references seg_modulo,
  constraint ia_prompt_tarea_ck check (tarea in ('CLASIFICACION','EXTRACCION','RESUMEN','IMPLICANCIA',
     'HABLANTE','DETECCION','VOTACION','CONSULTA_NL','COMENTARIOS'))
);

-- Versiones de prompt. Sólo una ACTIVA por prompt; la anterior queda
-- disponible para reversión (TR-11 refinamiento)
create table ia_prompt_version (
  prompt_version_id number generated by default on null as identity,
  prompt_id         number        not null,
  version           number        not null,
  plantilla         clob          not null,
  formato_salida    clob,
  estado            varchar2(20) default 'BORRADOR' not null,
  activada_por      varchar2(255),
  fecha_activacion  date,
  motivo_activacion varchar2(4000),
  notas             varchar2(4000),
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint ia_prompt_version_pk primary key (prompt_version_id),
  constraint ia_prompt_version_uk unique (prompt_id, version),
  constraint ia_prompt_version_pr_fk foreign key (prompt_id) references ia_prompt,
  constraint ia_prompt_version_est_ck check (estado in ('BORRADOR','ACTIVA','RETIRADA'))
);
create unique index ia_prompt_version_activa_ux on ia_prompt_version (
  case when estado = 'ACTIVA' then prompt_id end);

-- Lotes de prueba o reprocesamiento (TR-12): declaran alcance antes de ejecutar
create table ia_lote (
  lote_id               number generated by default on null as identity,
  tipo                  varchar2(20)  not null,
  modulo_codigo         varchar2(10)  not null,
  prompt_version_id     number        not null,
  cat_version_id        number,
  fecha_desde           date,
  fecha_hasta           date,
  ids_seleccionados     clob,
  tamano_muestra        number,
  registros_afectados   number,
  reemplazar_humanas    varchar2(1) default 'N' not null,
  autorizacion_reemplazo varchar2(4000),
  estado                varchar2(20) default 'BORRADOR' not null,
  procesados            number default 0 not null,
  omitidos              number default 0 not null,
  fallidos              number default 0 not null,
  modelo                varchar2(200),
  solicitado_por        varchar2(255) default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  confirmado_por        varchar2(255),
  fecha_confirmacion    date,
  fecha_inicio          timestamp,
  fecha_fin             timestamp,
  reintento_de_id       number,
  constraint ia_lote_pk primary key (lote_id),
  constraint ia_lote_tipo_ck check (tipo in ('PRUEBA','REPROCESO')),
  constraint ia_lote_est_ck check (estado in ('BORRADOR','CONFIRMADO','EN_PROCESO','COMPLETADO','CON_FALLOS','CANCELADO')),
  constraint ia_lote_rh_ck check (reemplazar_humanas in ('S','N')),
  constraint ia_lote_rh2_ck check (reemplazar_humanas = 'N' or autorizacion_reemplazo is not null),
  constraint ia_lote_pv_fk foreign key (prompt_version_id) references ia_prompt_version,
  constraint ia_lote_rei_fk foreign key (reintento_de_id) references ia_lote,
  constraint ia_lote_ids_json_ck check (ids_seleccionados is json)
);

-- Ejecución de IA: conserva prompt efectivo, modelo, versión de catálogo,
-- datos utilizados y resultado (TR-11, TR-12, Arq. §8)
create table ia_ejecucion (
  ejecucion_id      number generated by default on null as identity,
  tipo              varchar2(20)  default 'OPERATIVA' not null,
  prompt_version_id number,
  lote_id           number,
  cat_version_id    number,
  modelo            varchar2(200) not null,
  proveedor         varchar2(100),
  prompt_efectivo   clob,
  entrada           clob,
  salida            clob,
  salida_valida     varchar2(1) default 'S' not null,
  estado            varchar2(20) default 'OK' not null,
  error             varchar2(4000),
  duracion_ms       number,
  tokens_entrada    number,
  tokens_salida     number,
  entidad           varchar2(30),
  entidad_id        number,
  fecha             timestamp default systimestamp not null,
  usuario           varchar2(255) default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  constraint ia_ejecucion_pk primary key (ejecucion_id),
  constraint ia_ejecucion_tipo_ck check (tipo in ('OPERATIVA','PRUEBA','REPROCESO','CONSULTA')),
  constraint ia_ejecucion_est_ck check (estado in ('OK','ERROR','NO_ESTRUCTURADA')),
  constraint ia_ejecucion_pv_fk foreign key (prompt_version_id) references ia_prompt_version,
  constraint ia_ejecucion_lote_fk foreign key (lote_id) references ia_lote,
  constraint ia_ejecucion_cv_fk foreign key (cat_version_id) references cat_version,
  constraint ia_ejecucion_sal_json_ck check (salida is json)
);
create index ia_ejecucion_ent_ix on ia_ejecucion (entidad, entidad_id);
create index ia_ejecucion_lote_ix on ia_ejecucion (lote_id);

-- Integraciones configuradas (TR-13, PRE-02, RED-02, EC-02, EC-08)
create table int_integracion (
  integracion_codigo   varchar2(30)  not null,
  nombre               varchar2(200) not null,
  modulo_codigo        varchar2(10)  not null,
  patron               varchar2(30)  not null,
  endpoint             varchar2(1000),
  credencial_static_id varchar2(100),
  frecuencia_min       number default 60 not null,
  umbral_desfase_min   number default 120 not null,
  activa               varchar2(1) default 'S' not null,
  ultima_ejecucion_ok  timestamp,
  ultima_ejecucion     timestamp,
  ultimo_estado        varchar2(20),
  responsable          varchar2(255),
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint int_integracion_pk primary key (integracion_codigo),
  constraint int_integracion_mod_fk foreign key (modulo_codigo) references seg_modulo,
  constraint int_integracion_act_ck check (activa in ('S','N')),
  constraint int_integracion_pat_ck check (patron in ('PULL_API','PUSH','WEBHOOK','ARCHIVO','STREAMING','MANUAL'))
);

-- Historial de ejecuciones y errores (TR-13): distingue SIN_RESULTADOS de FALLIDA
create table int_ejecucion (
  ejecucion_id        number generated by default on null as identity,
  integracion_codigo  varchar2(30) not null,
  inicio              timestamp default systimestamp not null,
  fin                 timestamp,
  estado              varchar2(20) default 'EN_CURSO' not null,
  recibidos           number default 0 not null,
  nuevos              number default 0 not null,
  actualizados        number default 0 not null,
  duplicados          number default 0 not null,
  rechazados          number default 0 not null,
  etapa_error         varchar2(60),
  codigo_error        varchar2(60),
  mensaje_error       varchar2(4000),
  afecta_cobertura    varchar2(1) default 'N' not null,
  reintento_de_id     number,
  ejecutado_por       varchar2(255) default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  constraint int_ejecucion_pk primary key (ejecucion_id),
  constraint int_ejecucion_int_fk foreign key (integracion_codigo) references int_integracion,
  constraint int_ejecucion_rei_fk foreign key (reintento_de_id) references int_ejecucion,
  constraint int_ejecucion_est_ck check (estado in ('EN_CURSO','EXITOSA','SIN_RESULTADOS','PARCIAL','FALLIDA','REINTENTADA')),
  constraint int_ejecucion_afc_ck check (afecta_cobertura in ('S','N'))
);
create index int_ejecucion_int_ix on int_ejecucion (integracion_codigo, inicio);

-- Bandeja de incidencias / cuarentena de registros rechazados (PRE-02, TR-13)
create table int_incidencia (
  incidencia_id   number generated by default on null as identity,
  ejecucion_id    number        not null,
  origen_ref      varchar2(500),
  payload         clob,
  motivo          varchar2(30)  not null,
  detalle         varchar2(4000),
  estado          varchar2(20) default 'PENDIENTE' not null,
  resuelto_por    varchar2(255),
  fecha_resolucion date,
  fecha           timestamp default systimestamp not null,
  constraint int_incidencia_pk primary key (incidencia_id),
  constraint int_incidencia_eje_fk foreign key (ejecucion_id) references int_ejecucion,
  constraint int_incidencia_mot_ck check (motivo in ('ESQUEMA','INCOMPLETO','ERROR_INTEGRACION','DOCUMENTO_ILEGIBLE','DUPLICADO','OTRO')),
  constraint int_incidencia_est_ck check (estado in ('PENDIENTE','REPROCESADA','DESCARTADA'))
);
