--------------------------------------------------------------------------------
-- FARO · 01 · Base, seguridad, auditoría
-- HU: TR-01, TR-02, TR-03 · Arquitectura §10 (Seguridad, permisos y auditoría)
-- Convención de columnas de auditoría: CREADO_POR/CREADO_EN/MODIFICADO_POR/MODIFICADO_EN
-- se mantienen por triggers generados en 99_triggers_auditoria.sql
--------------------------------------------------------------------------------

-- Parámetros generales de la plataforma (modo IA, canales habilitados, SLA, etc.)
create table faro_parametro (
  codigo          varchar2(60)   not null,
  valor           varchar2(4000),
  descripcion     varchar2(1000),
  grupo           varchar2(60)   default 'GENERAL' not null,
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint faro_parametro_pk primary key (codigo)
);

-- Módulos de la plataforma: PRE (Prensa), RED (Redes), EC (Congreso), TR (Transversal)
create table seg_modulo (
  codigo      varchar2(10)  not null,
  nombre      varchar2(100) not null,
  descripcion varchar2(1000),
  icono       varchar2(60),
  orden       number(3)     default 0 not null,
  constraint seg_modulo_pk primary key (codigo)
);

-- Roles del sistema (ADMIN, ESPECIALISTA, USUARIO, FUNCIONARIO)
create table seg_rol (
  codigo      varchar2(30)  not null,
  nombre      varchar2(100) not null,
  descripcion varchar2(1000),
  constraint seg_rol_pk primary key (codigo)
);

-- Capacidades autorizables: consulta, edición, validación, administración, y
-- alcance de información (indicadores, menciones individuales, evidencias) (TR-02)
create table seg_capacidad (
  codigo      varchar2(30)  not null,
  nombre      varchar2(100) not null,
  descripcion varchar2(1000),
  orden       number(3) default 0 not null,
  constraint seg_capacidad_pk primary key (codigo)
);

-- Permisos por defecto que otorga cada rol (plantilla); el permiso efectivo se
-- materializa por usuario y módulo en SEG_PERMISO
create table seg_rol_capacidad (
  rol_codigo       varchar2(30) not null,
  capacidad_codigo varchar2(30) not null,
  constraint seg_rol_capacidad_pk primary key (rol_codigo, capacidad_codigo),
  constraint seg_rol_capacidad_rol_fk foreign key (rol_codigo) references seg_rol,
  constraint seg_rol_capacidad_cap_fk foreign key (capacidad_codigo) references seg_capacidad
);

-- Usuarios autorizados. La autenticación se delega al SSO institucional;
-- FARO sólo conserva la autorización (TR-01, Arq. §10)
create table seg_usuario (
  usuario_id      number generated by default on null as identity,
  usuario_sso     varchar2(255) not null,
  nombre          varchar2(200) not null,
  correo          varchar2(255),
  area            varchar2(200),
  rol_codigo      varchar2(30)  not null,
  tipo            varchar2(20)  default 'INTERNO' not null,
  estado          varchar2(20)  default 'ACTIVO' not null,
  telefono_alerta varchar2(30),
  teams_id        varchar2(255),
  fecha_alta      date default sysdate not null,
  fecha_baja      date,
  motivo_baja     varchar2(1000),
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint seg_usuario_pk primary key (usuario_id),
  constraint seg_usuario_sso_uk unique (usuario_sso),
  constraint seg_usuario_rol_fk foreign key (rol_codigo) references seg_rol,
  constraint seg_usuario_tipo_ck check (tipo in ('INTERNO','FUNCIONARIO')),
  constraint seg_usuario_estado_ck check (estado in ('ACTIVO','INACTIVO'))
);

-- Permiso efectivo por usuario, módulo y capacidad. Los permisos ADICIONALES
-- (excepcionales, p.ej. para funcionarios) exigen alcance, aprobador, motivo y
-- vigencia, y se revocan automáticamente al vencer (TR-03)
create table seg_permiso (
  permiso_id        number generated by default on null as identity,
  usuario_id        number        not null,
  modulo_codigo     varchar2(10)  not null,
  capacidad_codigo  varchar2(30)  not null,
  tipo              varchar2(20)  default 'ORDINARIO' not null,
  alcance           varchar2(1000),
  motivo            varchar2(1000),
  aprobador         varchar2(255),
  fecha_inicio      date default trunc(sysdate) not null,
  fecha_fin         date,
  estado            varchar2(20)  default 'VIGENTE' not null,
  revocado_por      varchar2(255),
  fecha_revocacion  date,
  motivo_revocacion varchar2(1000),
  creado_por      varchar2(255)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  creado_en       date           default on null sysdate not null,
  modificado_por  varchar2(255),
  modificado_en   date,
  constraint seg_permiso_pk primary key (permiso_id),
  constraint seg_permiso_usr_fk foreign key (usuario_id) references seg_usuario,
  constraint seg_permiso_mod_fk foreign key (modulo_codigo) references seg_modulo,
  constraint seg_permiso_cap_fk foreign key (capacidad_codigo) references seg_capacidad,
  constraint seg_permiso_tipo_ck check (tipo in ('ORDINARIO','ADICIONAL')),
  constraint seg_permiso_estado_ck check (estado in ('VIGENTE','VENCIDO','REVOCADO')),
  constraint seg_permiso_adic_ck check (
     tipo = 'ORDINARIO'
     or (alcance is not null and motivo is not null and aprobador is not null and fecha_fin is not null)),
  constraint seg_permiso_fechas_ck check (fecha_fin is null or fecha_fin >= fecha_inicio)
);
create index seg_permiso_usr_ix on seg_permiso (usuario_id, modulo_codigo, capacidad_codigo, estado);

-- Bitácora de eventos de auditoría de negocio (Arq. §10.1)
create table aud_evento (
  evento_id       number generated by default on null as identity,
  fecha           timestamp default systimestamp not null,
  usuario         varchar2(255) default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  tipo_evento     varchar2(40)  not null,
  modulo_codigo   varchar2(10),
  entidad         varchar2(60)  not null,
  entidad_id      varchar2(100),
  valor_anterior  clob,
  valor_nuevo     clob,
  motivo          varchar2(4000),
  constraint aud_evento_pk primary key (evento_id),
  constraint aud_evento_tipo_ck check (tipo_evento in (
     'PERMISO','USUARIO','CATALOGO','VALIDACION','CORRECCION','DESCARTE','ESTADO',
     'REPROCESO','CIERRE','REAPERTURA','REPORTE','ENVIO','PROMPT','FUSION',
     'INTEGRACION','ALERTA','HITO','DUPLICADO','POLITICA','MIGRACION','OTRO')),
  constraint aud_evento_ant_json_ck check (valor_anterior is json),
  constraint aud_evento_nue_json_ck check (valor_nuevo is json)
);
create index aud_evento_ent_ix on aud_evento (entidad, entidad_id);
create index aud_evento_fec_ix on aud_evento (fecha);

-- Registro de consultas realizadas (búsquedas, perfiles, NLQ, exportaciones)
-- (TR-03 "las consultas realizadas deben quedar registradas", TR-21)
create table aud_consulta (
  consulta_id   number generated by default on null as identity,
  fecha         timestamp default systimestamp not null,
  usuario       varchar2(255) default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
  tipo          varchar2(30)  not null,
  pagina        varchar2(100),
  parametros    clob,
  resultados    number,
  constraint aud_consulta_pk primary key (consulta_id),
  constraint aud_consulta_tipo_ck check (tipo in ('BUSQUEDA','PERFIL','NLQ','EXPORTACION','EVIDENCIA','INDICADOR','REPORTE')),
  constraint aud_consulta_par_json_ck check (parametros is json)
);
create index aud_consulta_usr_ix on aud_consulta (usuario, fecha);
